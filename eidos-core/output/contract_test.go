// goSyntax is the comment spelling of a line-commented language.
func goSyntax() plugin.CommentSyntax {
	return plugin.CommentSyntax{
		Line:   []string{"//"},
		Blocks: []plugin.CommentBlock{{Open: "/*", Close: "*/"}},
	}
}

// blockSyntax is a language with block comments and nothing else.
func blockSyntax() plugin.CommentSyntax {
	return plugin.CommentSyntax{
		Blocks: []plugin.CommentBlock{{Open: "<!--", Close: "-->"}},
	}
}

// bodyText is the fixture body, blank line included: the frame's
// boundary is its own first blank line, never the body's.
const bodyText = "package svc\n\nfunc Load() {}\n"

// hexDigest is sha256 of bodyText in hex, computed outside this
// package, so the test pins the bytes and does not mirror the code.
// A malformed-frame case reuses it wherever the trailer needs a
// well-formed digest, so the parse continues to the line under test.
const hexDigest = "614193ef93d47f9a586ce9d422874980fd6690fcb657630610e96233cc5cd1dd"

// bodyHash is the trailer's claim over bodyText.
const bodyHash = "sha256:" + hexDigest

// stamped is the frame the fixture file produces, in full.
const stamped = "// Code generated by acme. DO NOT EDIT.\n" +
	"// acme:plugin acme-audit\n" +
	"// acme:plugin stubgen\n" +
	"// acme:source svc/store.go\n" +
	"\n" +
	bodyText +
	"// acme:provenance " + bodyHash + "\n"

// fixtureFile returns the rendered file the frame is built over.
func fixtureFile() plugin.RenderedFile {
	return plugin.RenderedFile{
		Name:    "store_stub.go",
		Plugins: []plugin.ID{"stubgen", "acme-audit"},
		Sources: []string{"svc/store.go"},
		Body:    []byte(bodyText),
	}
}

// tailOf returns a file's last output.TailSize bytes, or all of a
// shorter file, as a probe reads them.
func tailOf(b []byte) []byte {
	return b[max(len(b)-output.TailSize, 0):]
}

// contract composes the fixture contract, failing the test where
// the composition fails.
func contract(tb assert.TB, b output.Brand, s plugin.CommentSyntax) *output.Contract {
	tb.Helper()

	c, err := output.NewContract(b, s)
	assert.NoError(tb, err, "the fixture contract composes")
	return c
}

// The contract is what makes a generated file provable from its
// own bytes: a marker the ecosystem recognises, the derivation
// that attributes it, and a trailer that proves ownership and
// integrity with no state anywhere else.
func TestContract(t *testing.T) {
	t.Parallel()

	t.Run("NewContract", func(t *testing.T) {
		t.Parallel()

		invalid := []struct {
			name  string
			brand output.Brand
		}{
			{name: "returns an error for the empty brand", brand: ""},
			{name: "returns an error for a brand with an uppercase letter", brand: "Acme"},
			{name: "returns an error for a brand with a space", brand: "acme gen"},
			{name: "returns an error for a brand with a dot", brand: "acme.gen"},
			{name: "returns an error for a brand with an underscore", brand: "acme_gen"},
			{name: "returns an error for a brand with a slash", brand: "acme/gen"},
			{name: "returns an error for a brand with a colon", brand: "acme:gen"},
			{name: "returns an error for a brand opening with a digit", brand: "2acme"},
			{name: "returns an error for a brand opening with a hyphen", brand: "-acme"},
		}
		for _, tt := range invalid {
			t.Run(tt.name, func(t *testing.T) {
				t.Parallel()

				_, err := output.NewContract(tt.brand, goSyntax())
				assert.HasError(t, err, "the composition fails")
			})
		}

		valid := []struct {
			name  string
			brand output.Brand
		}{
			{name: "returns a contract for a lowercase brand", brand: "acme"},
			{name: "returns a contract for a brand with a hyphen", brand: "acme-gen"},
			{name: "returns a contract for a brand with a digit after its first letter", brand: "gen2"},
		}
		for _, tt := range valid {
			t.Run(tt.name, func(t *testing.T) {
				t.Parallel()

				_, err := output.NewContract(tt.brand, goSyntax())
				assert.NoError(t, err, "the composition succeeds")
			})
		}

		t.Run("returns an error for a syntax without a comment form", func(t *testing.T) {
			t.Parallel()

			_, err := output.NewContract("acme", plugin.CommentSyntax{})
			assert.HasError(t, err, "a language without comments has no place for the frame")
		})

		t.Run("frames with the block form where no line form exists", func(t *testing.T) {
			t.Parallel()

			out, err := contract(t, "acme", blockSyntax()).Stamp(fixtureFile())
			assert.NoError(t, err, "the block language stamps")
			assert.HasPrefix(t, string(out),
				"<!-- Code generated by acme. DO NOT EDIT. -->\n",
				"each frame line wraps in the first block form")
			assert.HasSuffix(t, string(out),
				"<!-- acme:provenance "+bodyHash+" -->\n",
				"the trailer wraps in the block form")
		})
	})

	t.Run("Brand", func(t *testing.T) {
		t.Parallel()

		t.Run("returns the name the contract stamps under", func(t *testing.T) {
			t.Parallel()

			assert.Equal(t, contract(t, "acme-gen", goSyntax()).Brand(), output.Brand("acme-gen"),
				"the brand is the composed one")
		})
	})

	t.Run("Stamp", func(t *testing.T) {
		t.Parallel()

		t.Run("returns the marker, the sorted derivation, the body and the trailer", func(t *testing.T) {
			t.Parallel()

			out, err := contract(t, "acme", goSyntax()).Stamp(fixtureFile())
			assert.NoError(t, err, "the fixture stamps")
			assert.Equal(t, string(out), stamped, "the frame is pinned")
		})

		t.Run("returns the same bytes twice", func(t *testing.T) {
			t.Parallel()

			c := contract(t, "acme", goSyntax())
			first, err := c.Stamp(fixtureFile())
			assert.NoError(t, err, "the first stamp succeeds")
			second, err := c.Stamp(fixtureFile())
			assert.NoError(t, err, "the second stamp succeeds")
			assert.Equal(t, string(second), string(first), "the stamp has no clock and no counter")
		})

		t.Run("writes the derivation sorted without duplicates", func(t *testing.T) {
			t.Parallel()

			f := fixtureFile()
			f.Plugins = []plugin.ID{"stubgen", "acme-audit", "stubgen"}
			f.Sources = []string{"svc/store.go", "svc/store.go"}
			out, err := contract(t, "acme", goSyntax()).Stamp(f)
			assert.NoError(t, err, "the unsorted fixture stamps")
			assert.Equal(t, string(out), stamped, "the frame is the sorted one")
		})

		t.Run("writes the marker and the trailer alone for a file without derivation", func(t *testing.T) {
			t.Parallel()

			out, err := contract(t, "acme", goSyntax()).Stamp(plugin.RenderedFile{
				Name: "registry.go", Body: []byte("package svc\n"),
			})
			assert.NoError(t, err, "a plan file stamps")
			assert.Equal(t, string(out),
				"// Code generated by acme. DO NOT EDIT.\n"+
					"\n"+
					"package svc\n"+
					"// acme:provenance sha256:"+
					"29fe8614d6d9cb93b43663f869d741c2da0a14c530532c2cd9b6f19f31c3dec6\n",
				"the frame has no derivation line")
		})

		refusals := []struct {
			name string
			file plugin.RenderedFile
		}{
			{
				name: "returns an error for a body without a final newline",
				file: plugin.RenderedFile{Body: []byte("package svc")},
			},
			{
				name: "returns an error for an empty body",
				file: plugin.RenderedFile{},
			},
			{
				name: "returns an error for a body with a carriage return",
				file: plugin.RenderedFile{Body: []byte("package svc\r\n")},
			},
			{
				name: "returns an error for a body that is not UTF-8",
				file: plugin.RenderedFile{Body: []byte("package svc // \xff\n")},
			},
			{
				name: "returns an error for a body opening with a byte order mark",
				file: plugin.RenderedFile{Body: []byte(string(rune(0xFEFF)) + "package svc\n")},
			},
			{
				name: "returns an error for a body with a byte order mark after its first character",
				file: plugin.RenderedFile{Body: []byte("package svc\n" + string(rune(0xFEFF)) + "\n")},
			},
			{
				name: "returns an error for a plugin name with a line break",
				file: plugin.RenderedFile{Plugins: []plugin.ID{"stub\ngen"}, Body: []byte("package svc\n")},
			},
			{
				name: "returns an error for a source with a line break",
				file: plugin.RenderedFile{Sources: []string{"svc\n/store.go"}, Body: []byte("package svc\n")},
			},
			{
				name: "returns an error for an empty plugin name",
				file: plugin.RenderedFile{Plugins: []plugin.ID{""}, Body: []byte("package svc\n")},
			},
		}
		for _, tt := range refusals {
			t.Run(tt.name, func(t *testing.T) {
				t.Parallel()

				_, err := contract(t, "acme", goSyntax()).Stamp(tt.file)
				assert.HasError(t, err, "the stamp fails")
			})
		}
	})

	t.Run("Read", func(t *testing.T) {
		t.Parallel()

		t.Run("returns the record of a frame under any brand", func(t *testing.T) {
			t.Parallel()

			p, held := output.Read([]byte(stamped))
			assert.True(t, held, "the frame parses without a contract")
			assert.Equal(t, p.Brand, output.Brand("acme"), "the record has the claimed brand")
			assert.Equal(t, p.Plugins, []plugin.ID{"acme-audit", "stubgen"}, "the record has every plugin line")
			assert.Equal(t, p.Sources, []string{"svc/store.go"}, "the record has every source line")
			assert.Equal(t, p.Hash, bodyHash, "the record has the attested hash")
		})

		t.Run("returns the record of a block-commented frame", func(t *testing.T) {
			t.Parallel()

			out, err := contract(t, "acme", blockSyntax()).Stamp(fixtureFile())
			assert.NoError(t, err, "the block language stamps")
			p, held := output.Read(out)
			assert.True(t, held, "the block frame parses")
			assert.Equal(t, p.Sources, []string{"svc/store.go"}, "the derivation reads through the block form")
		})

		t.Run("skips a key it does not know", func(t *testing.T) {
			t.Parallel()

			grown := strings.Replace(stamped,
				"// acme:source svc/store.go\n",
				"// acme:source svc/store.go\n// acme:plan go-services\n", 1)
			p, held := output.Read([]byte(grown))
			assert.True(t, held, "the unknown key does not break the parse")
			assert.Equal(t, p.Sources, []string{"svc/store.go"}, "the known keys read unchanged")
		})

		unreadable := []struct {
			name    string
			stamped string
		}{
			{name: "reports false for an empty file", stamped: ""},
			{name: "reports false for a file without a frame", stamped: "package svc\n"},
			{
				name:    "reports false for a marker without a trailer",
				stamped: "// Code generated by acme. DO NOT EDIT.\n\npackage svc\n",
			},
			{
				name:    "reports false for a trailer naming no brand",
				stamped: "package svc\n:provenance " + bodyHash + "\n",
			},
			{
				name: "reports false for a trailer under a brand opening with a digit",
				stamped: "// Code generated by 2acme. DO NOT EDIT.\n\n" + bodyText +
					"// 2acme:provenance " + bodyHash + "\n",
			},
			{
				name:    "reports false for a digest cut short",
				stamped: "package svc\n// acme:provenance sha256:614193ef\n",
			},
			{
				name: "reports false for a digest outside hex",
				stamped: "package svc\n// acme:provenance sha256:" +
					strings.Repeat("z", len(hexDigest)) + "\n",
			},
			{
				name:    "reports false for a file that opens with code",
				stamped: "package svc\n// acme:provenance " + bodyHash + "\n",
			},
			{
				name: "reports false for a frame without the blank line that ends it",
				stamped: "// Code generated by acme. DO NOT EDIT.\n" +
					"// acme:provenance " + bodyHash + "\n",
			},
			{
				name: "reports false for a derivation line outside the comment form",
				stamped: "// Code generated by acme. DO NOT EDIT.\n" +
					"plain text\n\n" + bodyText +
					"// acme:provenance " + bodyHash + "\n",
			},
			{
				name: "reports false for a derivation line under another brand",
				stamped: "// Code generated by acme. DO NOT EDIT.\n" +
					"// rival:plugin stubgen\n\n" + bodyText +
					"// acme:provenance " + bodyHash + "\n",
			},
			{
				name: "reports false for a block-form line without its closer",
				stamped: "<!-- Code generated by acme. DO NOT EDIT. -->\n" +
					"<!-- acme:plugin stubgen\n\n" + bodyText +
					"<!-- acme:provenance " + bodyHash + " -->\n",
			},
		}
		for _, tt := range unreadable {
			t.Run(tt.name, func(t *testing.T) {
				t.Parallel()

				_, held := output.Read([]byte(tt.stamped))
				assert.False(t, held, "no record is read")
			})
		}
	})

	t.Run("HasTrailerKey", func(t *testing.T) {
		t.Parallel()

		block, err := contract(t, "acme", blockSyntax()).Stamp(fixtureFile())
		assert.NoError(t, err, "the block language stamps")
		tests := []struct {
			name string
			give []byte
			want bool
		}{
			{name: "reports true for the tail of a line-commented frame", give: tailOf([]byte(stamped)), want: true},
			{name: "reports true for the tail of a block-commented frame", give: tailOf(block), want: true},
			{name: "reports false for the tail of a file without a frame", give: tailOf([]byte(bodyText)), want: false},
		}
		for _, tt := range tests {
			t.Run(tt.name, func(t *testing.T) {
				t.Parallel()

				assert.Equal(t, output.HasTrailerKey(tt.give), tt.want,
					"the last TailSize bytes contain the key exactly where a trailer ends the file")
			})
		}
	})

	t.Run("Verify", func(t *testing.T) {
		t.Parallel()

		t.Run("returns the record of what Stamp produced", func(t *testing.T) {
			t.Parallel()

			c := contract(t, "acme", goSyntax())
			out, err := c.Stamp(fixtureFile())
			assert.NoError(t, err, "the fixture stamps")
			p, err := c.Verify(out)
			assert.NoError(t, err, "the file verifies")
			assert.Equal(t, p.Plugins, []plugin.ID{"acme-audit", "stubgen"}, "the record has the derivation")
		})

		broken := []struct {
			name    string
			stamped string
		}{
			{name: "returns an error for a file without a frame", stamped: "package svc\n"},
			{name: "returns an error for another brand's file", stamped: strings.ReplaceAll(stamped, "acme", "rival")},
			{
				name:    "returns an error for a body edited after stamping",
				stamped: strings.Replace(stamped, "func Load() {}", "func Load() { x() }", 1),
			},
			{name: "returns an error for bytes appended after the trailer", stamped: stamped + "func Extra() {}\n"},
			{name: "returns an error for a blank line appended after the trailer", stamped: stamped + "\n"},
		}
		for _, tt := range broken {
			t.Run(tt.name, func(t *testing.T) {
				t.Parallel()

				_, err := contract(t, "acme", goSyntax()).Verify([]byte(tt.stamped))
				assert.HasError(t, err, "the verification fails")
			})
		}
	})
}

// FuzzParse checks the frame's round trip over arbitrary derivation
// and body bytes: what [output.Contract.Stamp] writes, [output.Read]
// reads back exactly and [output.Contract.Verify] verifies, and a
// body edited by one byte afterwards fails verification. Read has
// no schema: the trailer names the brand and the comment form, so
// the property is stated against what stamping produced, not
// against a hand-written expectation.
//
// Truncation is deliberately not a property here. A body that ends
// in a well-formed trailer of its own makes the prefix up to that
// line a whole frame, which verifies as the file it is.
func FuzzParse(f *testing.F) {
	f.Add("acme", "stubgen", "svc/store.go", bodyText, 0)
	f.Add("acme", "acme-audit", "svc/store.go", "package svc\n", 7)
	f.Add("gen2", "x", "y", "\n", 1)
	f.Add("acme", "// acme:plugin stubgen", "// acme:provenance "+bodyHash,
		stamped, 3)
	// A stamped file nested in a body: the frame meets its own
	// grammar twice over.
	f.Add("acme", "stubgen", "svc/store.go",
		bodyText+"// acme:provenance "+bodyHash+"\n", 11)

	f.Fuzz(func(t *testing.T, brand, plug, src, body string, at int) {
		c, err := output.NewContract(output.Brand(brand), goSyntax())
		if err != nil {
			return // a brand outside the charset frames nothing
		}
		out, err := c.Stamp(plugin.RenderedFile{
			Plugins: []plugin.ID{plugin.ID(plug)},
			Sources: []string{src},
			Body:    []byte(body),
		})
		if err != nil {
			return // Stamp refused a value no frame line can contain, so nothing parses
		}

		got, held := output.Read(out)
		assert.True(t, held, "every stamped file has a frame Read finds")
		assert.Equal(t, got.Brand, output.Brand(brand),
			"the trailer names the brand that stamped it")
		assert.Equal(t, got.Plugins, []plugin.ID{plugin.ID(plug)},
			"the plugin reads back as written")
		assert.Equal(t, got.Sources, []string{src}, "the source reads back as written")
		verified, err := c.Verify(out)
		assert.NoError(t, err, "the contract verifies what it stamped")
		assert.Equal(t, verified, got, "the verified record is the one Read returns")

		edited := slices.Clone(out)
		// The body's last occurrence is the body itself or the
		// trailer that attests it. Either edit is one the trailer
		// stops claiming.
		edited[bytes.LastIndex(out, []byte(body))+index(at, len(body))] ^= 0x20
		_, err = c.Verify(edited)
		assert.HasError(t, err,
			"a body edited after stamping no longer hashes to what the trailer claims")
	})
}

// index folds an arbitrary fuzz integer into an offset inside a
// slice of that width.
func index(at, width int) int {
	at %= width
	if at < 0 {
		at += width
	}
	return at
}

// benchFiles returns n rendered files of a realistic size: a
// two-kilobyte body, two emitters and one source each.
func benchFiles(n int) []plugin.RenderedFile {
	body := append(bytes.Repeat([]byte("\tcall()\n"), 250), '\n')
	files := make([]plugin.RenderedFile, 0, n)
	for i := range n {
		at := "svc/pkg" + strconv.Itoa(i) + "/store.go"
		files = append(files, plugin.RenderedFile{
			Name:    "store_stub.go",
			Plugins: []plugin.ID{"stubgen", "acme-audit"},
			Sources: []string{at},
			Body:    body,
		})
	}
	return files
}

// BenchmarkStamp measures the frame at the canonical file count:
// 1000 files of two kilobytes, which is one sha256 pass over two
// megabytes plus the frame's own bytes. The digest dominates, and
// the rest is one buffer per file.
func BenchmarkStamp(b *testing.B) {
	b.ReportAllocs()

	c, err := output.NewContract("acme", goSyntax())
	if err != nil {
		b.Fatalf("NewContract: unexpected error: %v", err)
	}
	files := benchFiles(1_000)
	b.ResetTimer()
	for b.Loop() {
		for _, f := range files {
			if _, err := c.Stamp(f); err != nil {
				b.Fatalf("Stamp: unexpected error: %v", err)
			}
		}
	}
}
