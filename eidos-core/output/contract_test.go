// The allocations of the contract, which TestContractAllocs checks in
// the ordinary run and BenchmarkContract in a benchmark run.
const (
	// readAllocs is what reading the frame of a bench file allocates: the
	// trailer line and the frame's lines, each copied into a string the
	// record's values are parts of, and the record's lists of plugins and
	// of sources.
	readAllocs = 4
	// lineContractAllocs is a contract over a line comment form: the
	// contract and its opener.
	lineContractAllocs = 2
	// blockContractAllocs is a contract over a block comment form: the
	// contract, its opener and its closer.
	blockContractAllocs = 3
)

// bodyText is the fixture body, blank line included: the frame's
// boundary is its own first blank line, never the body's.
const bodyText = "package svc\n\nfunc Load() {}\n"

// hexDigest is sha256 of bodyText in hex, computed outside this
// package, so the test pins the bytes and does not mirror the code.
// A malformed-frame case reuses it wherever the trailer needs a
// well-formed digest, so the parse continues to the line under test.
const hexDigest = "614193ef93d47f9a586ce9d422874980fd6690fcb657630610e96233cc5cd1dd"

// bodyHash is the trailer's claim over bodyText.
const bodyHash = "sha256:" + hexDigest

// stamped is the frame the fixture file produces, in full.
const stamped = "// Code generated by acme. DO NOT EDIT.\n" +
	"// acme:plugin acme-audit\n" +
	"// acme:plugin stubgen\n" +
	"// acme:source svc/store.go\n" +
	"\n" +
	bodyText +
	"// acme:provenance " + bodyHash + "\n"

// framesRoundTrip is the property [FuzzParse] and its ForAll twin in
// [TestContract] state.
const framesRoundTrip = "Read must return what Stamp wrote, Verify must verify it, " +
	"and a body edited by one byte must fail Verify"

// The contract is what makes a generated file provable from its
// own bytes: a marker the ecosystem recognises, the derivation
// that attributes it, and a trailer that proves ownership and
// integrity with no state anywhere else.
func TestContract(t *testing.T) {
	t.Parallel()

	t.Run("Valid", func(t *testing.T) {
		t.Parallel()

		tests := []struct {
			name string
			give output.Brand
			want bool
		}{
			{name: "reports true for a lowercase brand", give: "acme", want: true},
			{name: "reports true for a brand with a hyphen", give: "acme-gen", want: true},
			{name: "reports true for a brand with a digit after its first letter", give: "gen2", want: true},
			{name: "reports false for the empty brand", give: ""},
			{name: "reports false for a brand with an uppercase letter", give: "Acme"},
			{name: "reports false for a brand with a space", give: "acme gen"},
			{name: "reports false for a brand with a dot", give: "acme.gen"},
			{name: "reports false for a brand with an underscore", give: "acme_gen"},
			{name: "reports false for a brand with a slash", give: "acme/gen"},
			{name: "reports false for a brand with a colon", give: "acme:gen"},
			{name: "reports false for a brand opening with a digit", give: "2acme"},
			{name: "reports false for a brand opening with a hyphen", give: "-acme"},
		}
		for _, tt := range tests {
			t.Run(tt.name, func(t *testing.T) {
				t.Parallel()

				assert.Equal(t, tt.give.Valid(), tt.want, "the brand's spelling decides")
			})
		}
	})

	t.Run("NewContract", func(t *testing.T) {
		t.Parallel()

		t.Run("returns an error for a brand that is not valid", func(t *testing.T) {
			t.Parallel()

			_, err := output.NewContract("Acme", goSyntax())
			assert.HasError(t, err, "the composition fails")
		})

		t.Run("returns an error for a syntax without a comment form", func(t *testing.T) {
			t.Parallel()

			_, err := output.NewContract("acme", plugin.CommentSyntax{})
			assert.HasError(t, err, "a language without comments has no place for the frame")
		})

		t.Run("frames with the line form where a language has both", func(t *testing.T) {
			t.Parallel()

			out, err := contract(t, "acme", goSyntax()).Stamp(fixtureFile())
			assert.NoError(t, err, "the fixture stamps")
			assert.HasPrefix(t, string(out), "// Code generated by acme. DO NOT EDIT.\n",
				"each frame line is a line comment")
		})

		t.Run("frames with the block form where no line form exists", func(t *testing.T) {
			t.Parallel()

			out, err := contract(t, "acme", blockSyntax()).Stamp(fixtureFile())
			assert.NoError(t, err, "the block language stamps")
			assert.HasPrefix(t, string(out),
				"<!-- Code generated by acme. DO NOT EDIT. -->\n",
				"each frame line wraps in the first block form")
			assert.HasSuffix(t, string(out),
				"<!-- acme:provenance "+bodyHash+" -->\n",
				"the trailer wraps in the block form")
		})
	})

	t.Run("Brand", func(t *testing.T) {
		t.Parallel()

		t.Run("returns the name the contract stamps under", func(t *testing.T) {
			t.Parallel()

			assert.Equal(t, contract(t, "acme-gen", goSyntax()).Brand(), output.Brand("acme-gen"),
				"the brand is the composed one")
		})
	})

	t.Run("Stamp", func(t *testing.T) {
		t.Parallel()

		t.Run("returns the file in its stamped frame", func(t *testing.T) {
			t.Parallel()

			out, err := contract(t, "acme", goSyntax()).Stamp(fixtureFile())
			assert.NoError(t, err, "the fixture stamps")
			assert.Equal(t, string(out), stamped, "the frame is pinned")
		})

		t.Run("returns the same bytes twice", func(t *testing.T) {
			t.Parallel()

			c := contract(t, "acme", goSyntax())
			first, err := c.Stamp(fixtureFile())
			assert.NoError(t, err, "the first stamp succeeds")
			second, err := c.Stamp(fixtureFile())
			assert.NoError(t, err, "the second stamp succeeds")
			assert.Equal(t, string(second), string(first), "the stamp has no clock and no counter")
		})

		t.Run("writes the derivation sorted without duplicates", func(t *testing.T) {
			t.Parallel()

			f := fixtureFile()
			f.Plugins = []plugin.ID{"stubgen", "acme-audit", "stubgen"}
			f.Sources = []string{"svc/store.go", "svc/store.go"}
			out, err := contract(t, "acme", goSyntax()).Stamp(f)
			assert.NoError(t, err, "the unsorted fixture stamps")
			assert.Equal(t, string(out), stamped, "the frame is the sorted one")
		})

		t.Run("writes a derivation longer than the stamp sorts on the stack", func(t *testing.T) {
			t.Parallel()

			f := fixtureFile()
			f.Plugins, f.Sources = nil, nil
			for i := range 10 {
				f.Plugins = append(f.Plugins, plugin.ID("gen"+strconv.Itoa(9-i)))
				f.Sources = append(f.Sources, "svc/"+strconv.Itoa(9-i)+".go")
			}
			out, err := contract(t, "acme", goSyntax()).Stamp(f)
			assert.NoError(t, err, "the file stamps")
			p, held := output.Read(out)
			assert.True(t, held, "the frame reads back")
			expect.Pairwise(t, p.Plugins, func(earlier, later plugin.ID) bool { return earlier < later },
				"the ten plugins are sorted")
			expect.Length(t, p.Sources, 10, "and every source is written")
		})

		t.Run("writes no derivation for a file without one", func(t *testing.T) {
			t.Parallel()

			out, err := contract(t, "acme", goSyntax()).Stamp(plugin.RenderedFile{
				Path: "gen/registry.go", Body: []byte("package svc\n"),
			})
			assert.NoError(t, err, "a plan file stamps")
			assert.Equal(t, string(out),
				"// Code generated by acme. DO NOT EDIT.\n"+
					"\n"+
					"package svc\n"+
					"// acme:provenance sha256:"+
					"29fe8614d6d9cb93b43663f869d741c2da0a14c530532c2cd9b6f19f31c3dec6\n",
				"the frame has no derivation line")
		})

		refusals := []struct {
			name string
			file plugin.RenderedFile
		}{
			{
				name: "returns an error for a body without a final newline",
				file: plugin.RenderedFile{Body: []byte("package svc")},
			},
			{
				name: "returns an error for an empty body",
				file: plugin.RenderedFile{},
			},
			{
				name: "returns an error for a body with a carriage return",
				file: plugin.RenderedFile{Body: []byte("package svc\r\n")},
			},
			{
				name: "returns an error for a body that is not UTF-8",
				file: plugin.RenderedFile{Body: []byte("package svc // \xff\n")},
			},
			{
				name: "returns an error for a body opening with a byte order mark",
				file: plugin.RenderedFile{Body: []byte(string(rune(0xFEFF)) + "package svc\n")},
			},
			{
				name: "returns an error for a body with a byte order mark after its first character",
				file: plugin.RenderedFile{Body: []byte("package svc\n" + string(rune(0xFEFF)) + "\n")},
			},
			{
				name: "returns an error for a plugin name with a line break",
				file: plugin.RenderedFile{Plugins: []plugin.ID{"stub\ngen"}, Body: []byte("package svc\n")},
			},
			{
				name: "returns an error for a source with a line break",
				file: plugin.RenderedFile{Sources: []string{"svc\n/store.go"}, Body: []byte("package svc\n")},
			},
			{
				name: "returns an error for an empty plugin name",
				file: plugin.RenderedFile{Plugins: []plugin.ID{""}, Body: []byte("package svc\n")},
			},
		}
		for _, tt := range refusals {
			t.Run(tt.name, func(t *testing.T) {
				t.Parallel()

				_, err := contract(t, "acme", goSyntax()).Stamp(tt.file)
				assert.HasError(t, err, "the stamp fails")
			})
		}
	})

	t.Run("Read", func(t *testing.T) {
		t.Parallel()

		t.Run("returns the record of a frame under any brand", func(t *testing.T) {
			t.Parallel()

			p, held := output.Read([]byte(stamped))
			assert.True(t, held, "the frame parses without a contract")
			assert.Equal(t, p.Brand, output.Brand("acme"), "the record has the claimed brand")
			assert.Equal(t, p.Plugins, []plugin.ID{"acme-audit", "stubgen"}, "the record has every plugin line")
			assert.Equal(t, p.Sources, []string{"svc/store.go"}, "the record has every source line")
			assert.Equal(t, p.Hash, bodyHash, "the record has the attested hash")
		})

		t.Run("returns the record of a block-commented frame", func(t *testing.T) {
			t.Parallel()

			out, err := contract(t, "acme", blockSyntax()).Stamp(fixtureFile())
			assert.NoError(t, err, "the block language stamps")
			p, held := output.Read(out)
			assert.True(t, held, "the block frame parses")
			assert.Equal(t, p.Sources, []string{"svc/store.go"}, "the derivation reads through the block form")
		})

		t.Run("skips a key it does not know", func(t *testing.T) {
			t.Parallel()

			grown := strings.Replace(stamped,
				"// acme:source svc/store.go\n",
				"// acme:source svc/store.go\n// acme:plan go-services\n", 1)
			p, held := output.Read([]byte(grown))
			assert.True(t, held, "the unknown key does not break the parse")
			assert.Equal(t, p.Sources, []string{"svc/store.go"}, "the known keys read unchanged")
		})

		unreadable := []struct {
			name    string
			stamped string
		}{
			{name: "reports false for an empty file", stamped: ""},
			{name: "reports false for a file without a frame", stamped: "package svc\n"},
			{
				name:    "reports false for a marker without a trailer",
				stamped: "// Code generated by acme. DO NOT EDIT.\n\npackage svc\n",
			},
			{
				name:    "reports false for a trailer naming no brand",
				stamped: "package svc\n:provenance " + bodyHash + "\n",
			},
			{
				name: "reports false for a trailer under a brand opening with a digit",
				stamped: "// Code generated by 2acme. DO NOT EDIT.\n\n" + bodyText +
					"// 2acme:provenance " + bodyHash + "\n",
			},
			{
				name:    "reports false for a digest cut short",
				stamped: "package svc\n// acme:provenance sha256:614193ef\n",
			},
			{
				name: "reports false for a digest outside hex",
				stamped: "package svc\n// acme:provenance sha256:" +
					strings.Repeat("z", len(hexDigest)) + "\n",
			},
			{
				name:    "reports false for a file that opens with code",
				stamped: "package svc\n// acme:provenance " + bodyHash + "\n",
			},
			{
				name: "reports false for a frame without the blank line that ends it",
				stamped: "// Code generated by acme. DO NOT EDIT.\n" +
					"// acme:provenance " + bodyHash + "\n",
			},
			{
				name: "reports false for a derivation line outside the comment form",
				stamped: "// Code generated by acme. DO NOT EDIT.\n" +
					"plain text\n\n" + bodyText +
					"// acme:provenance " + bodyHash + "\n",
			},
			{
				name: "reports false for a derivation line under another brand",
				stamped: "// Code generated by acme. DO NOT EDIT.\n" +
					"// rival:plugin stubgen\n\n" + bodyText +
					"// acme:provenance " + bodyHash + "\n",
			},
			{
				name: "reports false for a block-form line without its closer",
				stamped: "<!-- Code generated by acme. DO NOT EDIT. -->\n" +
					"<!-- acme:plugin stubgen\n\n" + bodyText +
					"<!-- acme:provenance " + bodyHash + " -->\n",
			},
		}
		for _, tt := range unreadable {
			t.Run(tt.name, func(t *testing.T) {
				t.Parallel()

				_, held := output.Read([]byte(tt.stamped))
				assert.False(t, held, "no record is read")
			})
		}
	})

	t.Run("HasTrailerKey", func(t *testing.T) {
		t.Parallel()

		block, err := contract(t, "acme", blockSyntax()).Stamp(fixtureFile())
		assert.NoError(t, err, "the block language stamps")
		tests := []struct {
			name string
			give []byte
			want bool
		}{
			{name: "reports true for the tail of a line-commented frame", give: tailOf([]byte(stamped)), want: true},
			{name: "reports true for the tail of a block-commented frame", give: tailOf(block), want: true},
			{name: "reports false for the tail of a file without a frame", give: tailOf([]byte(bodyText)), want: false},
		}
		for _, tt := range tests {
			t.Run(tt.name, func(t *testing.T) {
				t.Parallel()

				assert.Equal(t, output.HasTrailerKey(tt.give), tt.want,
					"the last TailSize bytes contain the key exactly where a trailer ends the file")
			})
		}
	})

	t.Run("Verify", func(t *testing.T) {
		t.Parallel()

		t.Run("returns the record of what Stamp produced", func(t *testing.T) {
			t.Parallel()

			c := contract(t, "acme", goSyntax())
			out, err := c.Stamp(fixtureFile())
			assert.NoError(t, err, "the fixture stamps")
			p, err := c.Verify(out)
			assert.NoError(t, err, "the file verifies")
			assert.Equal(t, p.Plugins, []plugin.ID{"acme-audit", "stubgen"}, "the record has the derivation")
		})

		broken := []struct {
			name    string
			stamped string
		}{
			{name: "returns an error for a file without a frame", stamped: "package svc\n"},
			{name: "returns an error for another brand's file", stamped: strings.ReplaceAll(stamped, "acme", "rival")},
			{
				name:    "returns an error for a body edited after stamping",
				stamped: strings.Replace(stamped, "func Load() {}", "func Load() { x() }", 1),
			},
			{name: "returns an error for bytes appended after the trailer", stamped: stamped + "func Extra() {}\n"},
			{name: "returns an error for a blank line appended after the trailer", stamped: stamped + "\n"},
		}
		for _, tt := range broken {
			t.Run(tt.name, func(t *testing.T) {
				t.Parallel()

				_, err := contract(t, "acme", goSyntax()).Verify([]byte(tt.stamped))
				assert.HasError(t, err, "the verification fails")
			})
		}

		t.Run("returns the record of any stamp and an error after any edit of its body", func(t *testing.T) {
			t.Parallel()

			prop.ForAll(t, framesRoundTrip, roundTrips)
		})
	})
}

// A stamp allocates the bytes it returns, and nothing else, a read of a
// frame allocates its record, and a contract allocates itself and its
// comment spellings. The check runs alone, because the count includes
// every goroutine's allocations.
func TestContractAllocs(t *testing.T) {
	brand := output.Brand("acme-gen2")
	valid := false
	assert.MaxAllocs(t, func() { valid = brand.Valid() }, 0, "Valid allocates nothing")
	assert.True(t, valid, "Valid reports true for a valid brand")

	line, block := goSyntax(), blockSyntax()
	var (
		built *output.Contract
		err   error
	)
	assert.MaxAllocs(t, func() { built, err = output.NewContract("acme", line) }, lineContractAllocs,
		"NewContract allocates the contract and its opener")
	assert.NoError(t, err, "the line contract composes")
	assert.MaxAllocs(t, func() { built, err = output.NewContract("acme", block) }, blockContractAllocs,
		"NewContract allocates the contract, its opener and its closer")
	assert.NoError(t, err, "the block contract composes")

	var got output.Brand
	assert.MaxAllocs(t, func() { got = built.Brand() }, 0, "Brand allocates nothing")
	assert.Equal(t, got, output.Brand("acme"), "Brand returns the contract's brand")

	c := contract(t, "acme", goSyntax())
	f := benchFiles(1)[0]
	out, err := c.Stamp(f)
	assert.NoError(t, err, "the bench file stamps")
	assert.MaxAllocs(t, func() { _, err = c.Stamp(f) }, 1, "Stamp allocates the bytes it returns")
	assert.NoError(t, err, "the bench file stamps again")
	assert.MaxAllocs(t, func() { _, err = c.Verify(out) }, readAllocs, "Verify allocates the record it reads")
	assert.NoError(t, err, "the stamped file verifies")
	var held bool
	assert.MaxAllocs(t, func() { _, held = output.Read(out) }, readAllocs, "Read allocates the record it reads")
	assert.True(t, held, "Read finds the frame")
	tail := tailOf(out)
	assert.MaxAllocs(t, func() { held = output.HasTrailerKey(tail) }, 0, "HasTrailerKey allocates nothing")
	assert.True(t, held, "HasTrailerKey finds the key")
}

// BenchmarkContract measures the frame of a file of a realistic size, a
// two-kilobyte body with two emitters and one source: the stamp, which
// is one sha256 pass over the body and the frame's own bytes, and the
// reads of the frame back. It also measures the composition of a
// contract and the checks of its brand.
func BenchmarkContract(b *testing.B) {
	b.Run("Valid", func(b *testing.B) {
		brand := output.Brand("acme-gen2")
		c := bench.Start(b).MaxAllocs(0)
		defer c.End()
		valid := false
		for c.Loop() {
			valid = brand.Valid()
		}
		assert.True(b, valid, "Valid reports true for a valid brand")
	})

	syntaxes := []struct {
		name   string
		syntax plugin.CommentSyntax
		allocs uint64
	}{
		{name: "a line comment form", syntax: goSyntax(), allocs: lineContractAllocs},
		{name: "a block comment form", syntax: blockSyntax(), allocs: blockContractAllocs},
	}
	b.Run("NewContract", func(b *testing.B) {
		for _, tt := range syntaxes {
			b.Run(tt.name, func(b *testing.B) {
				c := bench.Start(b).MaxAllocs(tt.allocs)
				defer c.End()
				var (
					got *output.Contract
					err error
				)
				for c.Loop() {
					got, err = output.NewContract("acme", tt.syntax)
				}
				assert.NoError(b, err, "the contract composes")
				assert.Equal(b, got.Brand(), output.Brand("acme"), "under the brand")
			})
		}
	})

	acme := contract(b, "acme", goSyntax())
	files := benchFiles(1_000)

	b.Run("Brand", func(b *testing.B) {
		c := bench.Start(b).MaxAllocs(0)
		defer c.End()
		var got output.Brand
		for c.Loop() {
			got = acme.Brand()
		}
		assert.Equal(b, got, output.Brand("acme"), "Brand returns the contract's brand")
	})

	b.Run("Stamp", func(b *testing.B) {
		c := bench.Start(b).MaxAllocs(1)
		defer c.End()
		var (
			out  []byte
			err  error
			next int
		)
		for c.Loop() {
			out, err = acme.Stamp(files[next%len(files)])
			next++
		}
		assert.NoError(b, err, "every stamp succeeds")
		assert.True(b, output.HasTrailerKey(tailOf(out)), "with its trailer")
	})

	stamped, err := acme.Stamp(files[0])
	assert.NoError(b, err, "the bench file stamps")

	b.Run("Verify", func(b *testing.B) {
		c := bench.Start(b).MaxAllocs(readAllocs)
		defer c.End()
		var got output.Provenance
		for c.Loop() {
			got, err = acme.Verify(stamped)
		}
		assert.NoError(b, err, "the stamped file verifies")
		assert.Length(b, got.Plugins, 2, "to its record")
	})

	b.Run("Read", func(b *testing.B) {
		c := bench.Start(b).MaxAllocs(readAllocs)
		defer c.End()
		var (
			got  output.Provenance
			held bool
		)
		for c.Loop() {
			got, held = output.Read(stamped)
		}
		assert.True(b, held, "the stamped file has a frame")
		assert.Length(b, got.Sources, 1, "with its source")
	})

	b.Run("HasTrailerKey", func(b *testing.B) {
		tail := tailOf(stamped)
		c := bench.Start(b).MaxAllocs(0)
		defer c.End()
		held := false
		for c.Loop() {
			held = output.HasTrailerKey(tail)
		}
		assert.True(b, held, "the tail has the trailer's key")
	})
}

// FuzzParse checks [framesRoundTrip] over derivation and body bytes
// nothing in this repository wrote. Read has no schema: the trailer
// names the brand and the comment form, so the property is stated
// against what stamping produced, not against a hand-written
// expectation. Each seed is the choices of one case: the brand, the
// plugin, the source and the body, each as a two-byte little-endian
// length and its bytes, then two bytes of the edited offset.
//
// Truncation is not a property here. A body that ends in a well-formed
// trailer of its own makes the prefix up to that line a whole frame,
// which verifies as the file it is.
func FuzzParse(f *testing.F) {
	seeds := []struct {
		brand, plug, src, body string
		at                     uint16
	}{
		{brand: "acme", plug: "stubgen", src: "svc/store.go", body: bodyText, at: 0},
		{brand: "acme", plug: "acme-audit", src: "svc/store.go", body: "package svc\n", at: 7},
		{brand: "gen2", plug: "x", src: "y", body: "\n", at: 1},
		{brand: "acme", plug: "// acme:plugin stubgen", src: "// acme:provenance " + bodyHash, body: stamped, at: 3},
		// A stamped file nested in a body: the frame meets its own
		// grammar twice over.
		{
			brand: "acme",
			plug:  "stubgen",
			src:   "svc/store.go",
			body:  bodyText + "// acme:provenance " + bodyHash + "\n",
			at:    11,
		},
	}
	for _, s := range seeds {
		var choices []byte
		for _, text := range []string{s.brand, s.plug, s.src, s.body} {
			choices = binary.LittleEndian.AppendUint16(choices, uint16(len(text)))
			choices = append(choices, text...)
		}
		f.Add(binary.LittleEndian.AppendUint16(choices, s.at))
	}

	prop.Fuzz(f, framesRoundTrip, roundTrips)
}

// roundTrips checks [framesRoundTrip] on a brand, a plugin, a source, a
// body and an offset in the body that the case draws. A brand outside
// the charset frames nothing, and Stamp refuses a value no frame line
// can contain, so neither has a frame to read.
func roundTrips(c *prop.Case) {
	brand := string(c.Draw(prop.Bytes(), "brand"))
	plug := string(c.Draw(prop.Bytes(), "plugin"))
	src := string(c.Draw(prop.Bytes(), "source"))
	body := string(c.Draw(prop.Bytes(), "body"))
	at := c.Draw(prop.Integer(0, math.MaxUint16), "at")

	framing, err := output.NewContract(output.Brand(brand), goSyntax())
	if err != nil {
		return
	}
	out, err := framing.Stamp(plugin.RenderedFile{
		Plugins: []plugin.ID{plugin.ID(plug)},
		Sources: []string{src},
		Body:    []byte(body),
	})
	if err != nil {
		return
	}

	got, held := output.Read(out)
	assert.True(c, held, "every stamped file must have a frame Read finds")
	assert.Equal(c, got.Brand, output.Brand(brand), "the trailer must name the brand that stamped it")
	assert.Equal(c, got.Plugins, []plugin.ID{plugin.ID(plug)}, "the plugin must read back as written")
	assert.Equal(c, got.Sources, []string{src}, "the source must read back as written")
	verified, err := framing.Verify(out)
	assert.NoError(c, err, "the contract must verify what it stamped")
	assert.Equal(c, verified, got, "the verified record must be the one Read returns")

	if body == "" {
		return
	}
	edited := slices.Clone(out)
	// The body's last occurrence is the body itself or the trailer that
	// attests it. Either edit is one the trailer stops claiming.
	edited[bytes.LastIndex(out, []byte(body))+at%len(body)] ^= 0x20
	_, err = framing.Verify(edited)
	assert.HasError(c, err, "a body edited after stamping must no longer hash to what the trailer claims")
}

// goSyntax is the comment spelling of a line-commented language.
func goSyntax() plugin.CommentSyntax {
	return plugin.CommentSyntax{
		Line:   []string{"//"},
		Blocks: []plugin.CommentBlock{{Open: "/*", Close: "*/"}},
	}
}

// blockSyntax is a language with block comments and nothing else.
func blockSyntax() plugin.CommentSyntax {
	return plugin.CommentSyntax{
		Blocks: []plugin.CommentBlock{{Open: "<!--", Close: "-->"}},
	}
}

// fixtureFile returns the rendered file the frame is built over.
