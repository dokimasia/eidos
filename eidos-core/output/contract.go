// The frame's fixed spellings. The marker is what a toolchain
// recognises as generated code. The keys are the grammar a reader
// parses the derivation and the trailer with.
const (
	// markerPrefix and markerSuffix bracket the brand on the first
	// line, the spelling Go's go/ast reads as generated.
	markerPrefix = "Code generated by "
	markerSuffix = ". DO NOT EDIT."
	// keyPlugin and keySource label the derivation lines.
	keyPlugin = "plugin"
	keySource = "source"
	// keyProvenance labels the trailer.
	keyProvenance = "provenance"
	// hashPrefix names the digest, so the trailer remains readable
	// when a second digest is admitted beside it.
	hashPrefix = "sha256:"
	// hashLen is the hex width of a sha256 digest.
	hashLen = sha256.Size * 2
	// trailerKey opens a trailer's record: the provenance key and the
	// digest's name.
	trailerKey = ":" + keyProvenance + " " + hashPrefix
)

// derivationScratch is how many plugins, and how many sources, a stamp
// sorts on the stack. A file with more grows its derivation onto the
// heap.
const derivationScratch = 8

// TailSize is how many final bytes of a stamped file contain its
// trailer's key. The key, the digest, the comment's closer and the
// final line break end the file, 84 bytes and the closer, so 128
// bytes contain the key for every closer up to 44 bytes, its
// leading space included.
const TailSize = 128

// byteOrderMark is U+FEFF. The text policy forbids it anywhere in
// a body. A stamped file starts with its marker line, and the Go
// scanner refuses the mark after a file's first character.
const byteOrderMark = 0xFEFF

// Brand names the tool built on the kernel: the name the marker
// attributes generation to, the trailer claims ownership under,
// and a directive carrier opens with. A lowercase letter, then
// lowercase letters, digits and hyphens, nothing else, so the brand
// is safe in a comment line, a frame key, a directory name and a
// carrier mark without escaping.
//
// There is no default. Two tools built on the kernel and run in
// one repository must never prove ownership of each other's
// files or read each other's carriers, so every consumer states its
// own name.
type Brand string

// Valid reports whether b is spelled the way the frame and the
// carrier mark require: a lowercase letter first, then lowercase
// letters, digits and hyphens. It allocates nothing.
func (b Brand) Valid() bool {
	if b == "" || b[0] < 'a' || b[0] > 'z' {
		return false
	}
	for i := range len(b) {
		if !brandByte(b[i]) {
			return false
		}
	}
	return true
}

// brandByte reports whether c may appear in a brand.
func brandByte(c byte) bool {
	return c >= 'a' && c <= 'z' || c >= '0' && c <= '9' || c == '-'
}

// Provenance is the record a stamped file contains in its own
// bytes: who generated it, from what, and the digest of the body
// the trailer attests.
type Provenance struct {
	// Brand is the name the trailer claims ownership under.
	Brand Brand
	// Plugins and Sources are the derivation lines, in file order,
	// which [Contract.Stamp] writes sorted.
	Plugins []plugin.ID
	Sources []string
	// Hash is the trailer's claim over the body: "sha256:" and the
	// hex digest. It covers the body alone, so a brand rename or a
	// derivation change leaves it untouched. The digest of the
	// whole stamped file is the sink's record, not this one.
	Hash string
}

// Contract stamps rendered files for one target and one brand:
// the marker the ecosystem recognises as generated code, the
// derivation lines that attribute the file, and the trailer that
// proves ownership and integrity. Every frame line is spelled
// through the language's own comment form.
//
// # Concurrency
//
// A Contract is immutable after [NewContract] and safe for
// concurrent use.
//
// # Allocation contract
//
// [Contract.Stamp] allocates the bytes it returns. [Contract.Verify]
// and [Read] allocate the record they return: the trailer line and the
// frame's lines, each copied into one string that the record's values
// are parts of, and the record's lists of plugins and of sources. Read
// allocates nothing for bytes whose final line contains no trailer key.
type Contract struct {
	brand  Brand
	opener string
	closer string
}

// NewContract composes the stamp for one target.
//
// It refuses a brand outside [Brand.Valid] and a syntax with
// neither a line form nor a block form, because a language without
// comments has no place for the frame. The line form is
// preferred where a language has both: one line comment per frame
// line reads in every editor and diffs one line per change.
//
// # Allocation contract
//
// NewContract allocates the contract and its opener, and for a block
// form its closer: two allocations for a line form, three for a block
// form.
func NewContract(b Brand, s plugin.CommentSyntax) (*Contract, error) {
	if !b.Valid() {
		return nil, fmt.Errorf(
			"output: %q is not a brand: use a lowercase letter followed by lowercase letters, digits and hyphens",
			string(b),
		)
	}
	c := &Contract{brand: b}
	switch {
	case len(s.Line) > 0 && s.Line[0] != "":
		c.opener = s.Line[0] + " "
	case len(s.Blocks) > 0 && s.Blocks[0].Open != "" && s.Blocks[0].Close != "":
		c.opener = s.Blocks[0].Open + " "
		c.closer = " " + s.Blocks[0].Close
	default:
		return nil, errors.New(
			"output: the comment syntax has neither a line form nor a block form",
		)
	}
	return c, nil
}

// Brand returns the name this contract stamps under. It allocates
// nothing.
func (c *Contract) Brand() Brand { return c.brand }

// Stamp returns the finished bytes: the marker line, one
// derivation line per plugin and per source, one blank line, the
// file's body unchanged, and the trailer as the final line. The
// derivation is sorted and deduplicated here, so two renderers
// listing one file's emitters in two orders stamp one frame.
//
// It refuses a body that does not end in a newline, contains a
// carriage return or a byte order mark, or is not valid UTF-8. It
// refuses a plugin or source that is empty or contains a line
// break. The text policy is UTF-8 without a byte order mark, with
// LF line ends, and each refused input breaks the frame or the
// policy. A formatter emitting CRLF is where that violation is
// fixed.
//
// # Allocation contract
//
// Stamp allocates once, for the bytes it returns, where every frame line
// is at most 96 bytes and the file has at most eight plugins and eight
// sources. It sorts the derivation in storage on the stack and writes
// the digest into the returned bytes.
func (c *Contract) Stamp(f plugin.RenderedFile) ([]byte, error) {
	if len(f.Body) == 0 || f.Body[len(f.Body)-1] != '\n' {
		return nil, errors.New("output: the body does not end in a newline")
	}
	if bytes.IndexByte(f.Body, '\r') >= 0 {
		return nil, errors.New(
			"output: the body contains a carriage return, and the text policy is LF",
		)
	}
	if !utf8.Valid(f.Body) {
		return nil, errors.New("output: the body is not valid UTF-8, and the text policy is UTF-8")
	}
	if bytes.ContainsRune(f.Body, byteOrderMark) {
		return nil, errors.New(
			"output: the body contains a byte order mark, and the text policy writes none",
		)
	}
	var pluginScratch, sourceScratch [derivationScratch]string
	plugins := pluginScratch[:0]
	for _, p := range f.Plugins {
		plugins = append(plugins, string(p))
	}
	plugins, err := derivation(plugins, keyPlugin)
	if err != nil {
		return nil, err
	}
	sources, err := derivation(append(sourceScratch[:0], f.Sources...), keySource)
	if err != nil {
		return nil, err
	}

	var out bytes.Buffer
	out.Grow(len(f.Body) + frameWidth(c, len(plugins)+len(sources)))
	c.line(&out, markerPrefix, string(c.brand), markerSuffix)
	for _, p := range plugins {
		c.line(&out, string(c.brand), ":", keyPlugin, " ", p)
	}
	for _, s := range sources {
		c.line(&out, string(c.brand), ":", keySource, " ", s)
	}
	out.WriteByte('\n')
	out.Write(f.Body)
	out.WriteString(c.opener)
	out.WriteString(string(c.brand))
	out.WriteString(trailerKey)
	out.Write(appendHex(out.AvailableBuffer(), f.Body))
	out.WriteString(c.closer)
	out.WriteByte('\n')
	return out.Bytes(), nil
}

// Verify reads a stamped file back and checks it whole: the frame
// parses, the trailer names this contract's brand, the trailer
// is the file's final line, and its digest matches the body.
//
// It returns the record it verified. Anything appended after the
// trailer, another brand's file, or a body edited since stamping
// returns an error naming what broke.
func (c *Contract) Verify(stamped []byte) (Provenance, error) { return verify(stamped, c.brand) }

// verify reads a stamped file back and checks it against one brand:
// the frame parses, the trailer names the brand, and the trailer's
// digest matches the body. It is the ownership proof the contract
// and the disk sink share.
func verify(stamped []byte, brand Brand) (Provenance, error) {
	f, held := parse(stamped)
	if !held {
		return Provenance{}, errors.New(
			"output: the bytes have no frame, so nothing here was generated",
		)
	}
	if f.record.Brand != brand {
		return Provenance{}, fmt.Errorf(
			"output: the file is branded %q, not %q",
			string(f.record.Brand), string(brand),
		)
	}
	if !attests(f.body, f.record.Hash) {
		return Provenance{}, fmt.Errorf(
			"output: the body hashes to %s and the trailer claims %s",
			digest(f.body), f.record.Hash,
		)
	}
	return f.record, nil
}

// Read parses the frame of any brand's stamped file: the marker,
// the derivation lines, and the trailer as the final line. It
// returns false where no frame is present.
//
// Read checks nothing. Pairing the record with an integrity check
// is [Contract.Verify]'s work, and reading another tool's record
// is how a run tells another tool's intact file from a
// hand-written one. A key the grammar does not know is skipped, so a record
// that grew a key still reads here.
func Read(stamped []byte) (Provenance, bool) {
	f, held := parse(stamped)
	if !held {
		return Provenance{}, false
	}
	return f.record, true
}

// HasTrailerKey reports whether bytes from a file's end contain the
// key a trailer opens its record with. A file whose last [TailSize]
// bytes contain no key has no frame [Read] parses, so a caller that
// probes the tail reads the whole file only when this reports true.
func HasTrailerKey(tail []byte) bool {
	return bytes.Contains(tail, []byte(trailerKey))
}

// frame is one parsed stamped file: the record it contains and the
// body its trailer attests.
type frame struct {
	record Provenance
	body   []byte
}

// parse reads a stamped file's frame without being told the brand or
// the comment form, because the trailer spells both. The digest key
// locates the trailer, the brand reads backwards from that key, and
// whatever precedes the brand is the comment opener every other frame
// line opens with. The one space after the opener makes the brand
// readable back out.
func parse(stamped []byte) (frame, bool) {
	if len(stamped) == 0 || stamped[len(stamped)-1] != '\n' {
		return frame{}, false
	}
	head := stamped[:len(stamped)-1]
	cut := bytes.LastIndexByte(head, '\n')
	if cut < 0 {
		return frame{}, false
	}
	at := bytes.Index(head[cut+1:], []byte(trailerKey))
	if at < 0 {
		return frame{}, false
	}
	trailer := string(head[cut+1:])
	start := at
	for start > 0 && brandByte(trailer[start-1]) {
		start--
	}
	brand := Brand(trailer[start:at])
	if !brand.Valid() {
		return frame{}, false
	}
	digestAt := at + len(trailerKey)
	hashEnd := digestAt + hashLen
	if hashEnd > len(trailer) || !isHex(trailer[digestAt:hashEnd]) {
		return frame{}, false
	}
	c := Contract{
		brand:  brand,
		opener: trailer[:start],
		closer: trailer[hashEnd:],
	}
	return c.head(stamped[:cut+1], trailer[digestAt-len(hashPrefix):hashEnd])
}

// head reads the frame above the body: the marker, the derivation
// lines, and the blank line that ends them. Everything after that
// line is the body, byte for byte. The frame's lines copy into one
// string, which the record's derivation values are parts of, so the
// record keeps none of the body.
func (c *Contract) head(above []byte, hash string) (frame, bool) {
	end := bytes.Index(above, []byte("\n\n"))
	if end < 0 {
		return frame{}, false
	}
	marker, derivation, _ := strings.Cut(string(above[:end+1]), "\n")
	if !c.marker(marker) {
		return frame{}, false
	}
	plugins, sources := 0, 0
	for line := range strings.Lines(derivation) {
		key, _, held := c.entry(strings.TrimSuffix(line, "\n"))
		if !held {
			return frame{}, false
		}
		switch key {
		case keyPlugin:
			plugins++
		case keySource:
			sources++
		}
	}

	rec := Provenance{Brand: c.brand, Hash: hash}
	if plugins > 0 {
		rec.Plugins = make([]plugin.ID, 0, plugins)
	}
	if sources > 0 {
		rec.Sources = make([]string, 0, sources)
	}
	for line := range strings.Lines(derivation) {
		key, value, _ := c.entry(strings.TrimSuffix(line, "\n"))
		switch key {
		case keyPlugin:
			rec.Plugins = append(rec.Plugins, plugin.ID(value))
		case keySource:
			rec.Sources = append(rec.Sources, value)
		}
	}
	return frame{record: rec, body: above[end+2:]}, true
}

// marker reports whether a line is the frame's marker under the
// contract's brand and comment form.
func (c *Contract) marker(line string) bool {
	text, held := strings.CutPrefix(line, c.opener)
	if !held {
		return false
	}
	if text, held = strings.CutPrefix(text, markerPrefix); !held {
		return false
	}
	if text, held = strings.CutPrefix(text, string(c.brand)); !held {
		return false
	}
	if text, held = strings.CutPrefix(text, markerSuffix); !held {
		return false
	}
	return text == c.closer
}

// entry splits one derivation line into its key and value.
func (c *Contract) entry(line string) (key, value string, held bool) {
	text, held := strings.CutPrefix(line, c.opener)
	if !held {
		return "", "", false
	}
	text, held = strings.CutSuffix(text, c.closer)
	if !held {
		return "", "", false
	}
	text, held = strings.CutPrefix(text, string(c.brand))
	if !held {
		return "", "", false
	}
	text, held = strings.CutPrefix(text, ":")
	if !held {
		return "", "", false
	}
	return strings.Cut(text, " ")
}

// isHex reports whether every byte of s is a hex digit, in either
// case.
func isHex(s string) bool {
	for i := range len(s) {
		switch c := s[i]; {
		case c >= '0' && c <= '9', c >= 'a' && c <= 'f', c >= 'A' && c <= 'F':
		default:
			return false
		}
	}
	return true
}

// line writes one frame line in the language's comment form,
// taking its text in parts so a frame costs no string joins.
func (c *Contract) line(out *bytes.Buffer, parts ...string) {
	out.WriteString(c.opener)
	for _, part := range parts {
		out.WriteString(part)
	}
	out.WriteString(c.closer)
	out.WriteByte('\n')
}

// frameWidth estimates the frame's byte cost, so one stamp
// allocates once.
func frameWidth(c *Contract, entries int) int {
	const generous = 96
	return (entries + 3) * (len(c.opener) + len(c.closer) + generous)
}

// derivation sorts and deduplicates one set of derivation values,
// refusing a value no line can contain.
func derivation(values []string, key string) ([]string, error) {
	slices.Sort(values)
	values = slices.Compact(values)
	for _, v := range values {
		if v == "" {
			return nil, fmt.Errorf("output: an empty %s name attributes nothing", key)
		}
		if strings.ContainsAny(v, "\r\n") {
			return nil, fmt.Errorf(
				"output: the %s %q contains a line break, and a derivation line is one line",
				key, v,
			)
		}
	}
	return values, nil
}

// digest returns the trailer's claim over body, the digest's name and
// its hex spelling, as one string: the string is its one allocation.
func digest(body []byte) string {
	var claim [len(hashPrefix) + hashLen]byte
	return string(appendHex(append(claim[:0], hashPrefix...), body))
}

// attests reports whether hash is the trailer's claim over body. It
// spells the claim on the stack and allocates nothing.
func attests(body []byte, hash string) bool {
	var claim [len(hashPrefix) + hashLen]byte
	return string(appendHex(append(claim[:0], hashPrefix...), body)) == hash
}

// appendHex appends the hex spelling of body's sha256 digest to dst,
// the trailer's claim without its prefix, and allocates only where dst
// has no room for it.
func appendHex(dst, body []byte) []byte {
	sum := sha256.Sum256(body)
	return hex.AppendEncode(dst, sum[:])
}
