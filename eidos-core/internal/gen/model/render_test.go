package model_test

import (
	"strings"
	"testing"

	"go.dokimi.dev/assert"

	"go.dokimi.dev/eidos/core/internal/gen/model"
)

// reachSchema has shapes that the kernel's own schema does not have.
// One kind walks to a fact only through a descent field. A kind with a
// fact has the marker as its descent field. Its field names test both
// sides of the acronym rule.
const reachSchema = "// Root contains things and states no fact itself.\n" +
	"type Root struct {\n" +
	"\tThings []*Thing `eidos:\"emit,walk\"`\n" +
	"}\n\n" +
	"// Thing states a fact and contains any declaration.\n" +
	"type Thing struct {\n" +
	"\tAsync  bool     `eidos:\"emit,fact=Async\"`\n" +
	"\tDecls  []Symbol `eidos:\"emit,walk\"`\n" +
	"\tIDList []string `eidos:\"both\"`\n" +
	"\tcount  int      `eidos:\"both\"`\n" +
	"}\n"

// gaugeSchema declares a node-side field of a type that the binary
// codec cannot encode.
const gaugeSchema = "// Gauge measures one thing.\n" +
	"type Gauge struct {\n" +
	"\tLevel float64 `eidos:\"node\"`\n" +
	"}\n"

// Rendering decides the spellings that a template emits. The cases read
// the generated bytes and not the view, because a caller sees the file
// and not the intermediate form.
func TestRender(t *testing.T) {
	t.Parallel()

	// generated returns one rendered file with its column padding
	// collapsed. A case then reads the spelling and not the alignment
	// that gofmt chose.
	generated := func(t *testing.T, path string) string {
		t.Helper()

		set, err := model.Generate(moduleRoot(t))
		assert.NoError(t, err, "the schema generates")
		assert.Contains(t, set, path, "the case reads a file of the generator")
		return strings.Join(strings.Fields(string(set[path])), " ")
	}

	// rendered is generated over a written schema and not the
	// kernel's own.
	rendered := func(t *testing.T, schema, path string) string {
		t.Helper()

		set, err := model.Generate(schemaModule(t, schema))
		assert.NoError(t, err, "the written schema generates")
		assert.Contains(t, set, path, "the case reads a file of the generator")
		return strings.Join(strings.Fields(string(set[path])), " ")
	}

	t.Run("JSON keys", func(t *testing.T) {
		t.Parallel()

		t.Run("lower an acronym as one word", func(t *testing.T) {
			t.Parallel()

			assert.That(t, generated(t, "node/kinds.gen.go")).
				Contains(`json:"id,omitzero"`, "an acronym lowers as one word").
				NotContains(`json:"iD`, "an acronym does not lower by its first letter alone")
		})

		t.Run("keep an ordinary name camel-cased", func(t *testing.T) {
			t.Parallel()

			assert.Contains(t, generated(t, "node/kinds.gen.go"), `json:"typeParams,omitzero"`,
				"an ordinary name camel-cases")
		})

		t.Run("break an acronym before the word that follows it", func(t *testing.T) {
			t.Parallel()

			assert.Contains(t, rendered(t, reachSchema, "node/kinds.gen.go"),
				`json:"idList,omitzero"`,
				"the last capital opens the next word, so IDList lowers to idList")
		})

		t.Run("leave a name that carries no capital", func(t *testing.T) {
			t.Parallel()

			assert.Contains(t, rendered(t, reachSchema, "node/kinds.gen.go"),
				`json:"count,omitzero"`,
				"a field already lowercase keeps its spelling")
		})
	})

	t.Run("sides", func(t *testing.T) {
		t.Parallel()

		t.Run("the node model has a position and no origin", func(t *testing.T) {
			t.Parallel()

			assert.That(t, generated(t, "node/kinds.gen.go")).
				Contains("Pos position.Pos", "the node model has a position").
				NotContains("Origin symbol.Identity", "the node model has no origin, because an origin is an emit field")
		})

		t.Run("the emit model has an origin and no position", func(t *testing.T) {
			t.Parallel()

			assert.That(t, generated(t, "emit/kinds.gen.go")).
				Contains("Origin", "the emit model has an origin").
				Contains("position.Pos{}", "the emit model returns the zero position")
		})

		t.Run("a slot exists on the emit side alone", func(t *testing.T) {
			t.Parallel()

			assert.Contains(t, generated(t, "emit/kinds.gen.go"), "Fields Slot[*Field]",
				"the emit model has slot storage")
			assert.NotContains(t, generated(t, "node/kinds.gen.go"), "Slot[",
				"the node model has no slot storage")
		})

		t.Run("the body exists on the emit side alone", func(t *testing.T) {
			t.Parallel()

			assert.Contains(t, generated(t, "emit/kinds.gen.go"), `json:"body,omitzero"`,
				"the emit callables have a body field")
			assert.NotContains(t, generated(t, "node/kinds.gen.go"), `json:"body,omitzero"`,
				"the node model has no body field")
		})

		t.Run("a marker field has the dispatching slice type", func(t *testing.T) {
			t.Parallel()

			assert.Contains(t, generated(t, "node/kinds.gen.go"), "Decls Symbols",
				"a marker-typed field is typed Symbols, so it can decode")
		})

		t.Run("the node model returns identities and the emit model does not", func(t *testing.T) {
			t.Parallel()

			assert.Contains(t, generated(t, "node/kinds.gen.go"),
				"func (x *Struct) Identity() symbol.Identity",
				"a node declaration returns its identity, so a traversal can index by one")
			assert.NotContains(t, generated(t, "emit/kinds.gen.go"),
				"Identity() symbol.Identity",
				"an emit declaration has an origin instead of an identity")
		})

		t.Run("a node kind without an identity field returns the zero identity", func(t *testing.T) {
			t.Parallel()

			assert.Contains(t, rendered(t, reachSchema, "node/kinds.gen.go"),
				"func (x *Thing) Identity() symbol.Identity { return symbol.Identity{} }",
				"a node kind without an ID field is not a declaration, so its identity is zero")
		})

		t.Run("a node side with a kind without an identity field declares Declaration", func(t *testing.T) {
			t.Parallel()

			assert.Contains(t, rendered(t, reachSchema, "node/walk.gen.go"), "type Declaration interface",
				"every node kind has an Identity method, so the node side declares the interface")
		})

		t.Run("an emit kind without an identity field has no Identity method", func(t *testing.T) {
			t.Parallel()

			assert.NotContains(t, rendered(t, reachSchema, "emit/kinds.gen.go"), "Identity()",
				"an emit kind has an origin and not an identity")
		})

		t.Run("the match surface generates per subject kind", func(t *testing.T) {
			t.Parallel()

			assert.That(t, generated(t, "match.gen.go")).
				Contains("func OnInterface[E Effect](h func(*InterfaceMatch, E) error) Rule",
					"a marked kind gets its constructor and Match type").
				NotContains("OnTypeParam", "an unmarked kind gets neither a constructor nor a Match type")
			assert.Contains(t, generated(t, "match.gen_test.go"), "func TestMatches",
				"the generated twin checks every kind against the lowering")
		})

		t.Run("the emit walk returns origins by function", func(t *testing.T) {
			t.Parallel()

			walk := generated(t, "emit/walk.gen.go")
			assert.Contains(t, walk,
				"func OriginOf(s symbol.Symbol) (symbol.Identity, bool)",
				"a subset of emit kinds has origin storage, so a function returns the origin")
			assert.NotContains(t, generated(t, "node/walk.gen.go"), "OriginOf",
				"the node side has identities, never origins")
		})

		t.Run("the node walk returns the declarations it yields", func(t *testing.T) {
			t.Parallel()

			walk := generated(t, "node/walk.gen.go")
			for _, want := range []string{
				"type Declaration interface",
				"func Declarations(s symbol.Symbol) iter.Seq[Declaration]",
			} {
				assert.Contains(t, walk, want,
					"the node walk returns the declarations it yields")
			}
			assert.NotContains(t, generated(t, "emit/walk.gen.go"), "Declaration",
				"only the node side declares the interface")
		})
	})

	t.Run("facts", func(t *testing.T) {
		t.Parallel()

		t.Run("a kind with a fact only in a child joins the traversal", func(t *testing.T) {
			t.Parallel()

			assert.That(t, rendered(t, reachSchema, "emit/facts.gen.go")).
				Contains("case *Root: for _, child := range x.Things { statedFacts(x, child, f) }",
					"a kind without a fact of its own still descends, because its child has the fact").
				NotContains("symbol.KindRoot:", "the kind states no fact directly, so the coverage check does not count it")
		})

		t.Run("a marker descent field takes a child of the enclosing kind", func(t *testing.T) {
			t.Parallel()

			assert.That(t, rendered(t, reachSchema, "emit/facts.gen_test.go")).
				Contains("child := &Thing{}", "a field that admits any kind takes a value of its own kind").
				Contains("child.Async = true", "the child states the first fact of its kind")
		})
	})

	t.Run("binary codec", func(t *testing.T) {
		t.Parallel()

		t.Run("writes a field that admits any kind through the kind switch", func(t *testing.T) {
			t.Parallel()

			assert.Contains(t, generated(t, "node/codec.gen.go"),
				"for _, child := range x.Decls { if err := w.symbol(child); err != nil { return err } }",
				"the codec writes the kind of each element before the element")
		})

		t.Run("returns no error from a kind without a field that admits any kind", func(t *testing.T) {
			t.Parallel()

			assert.Contains(t, generated(t, "node/codec.gen.go"),
				"func (w *binaryWriter) encodeTypeRef(x *TypeRef) {",
				"a type reference contains no field that admits any kind")
		})

		t.Run("returns an error from a kind with a descendant field that admits any kind", func(t *testing.T) {
			t.Parallel()

			assert.Contains(t, generated(t, "node/codec.gen.go"),
				"func (w *binaryWriter) encodePackage(x *Package) error {",
				"a package's files contain declaration lists that admit any kind")
		})

		t.Run("reads a field of one kind through the typed reader", func(t *testing.T) {
			t.Parallel()

			assert.Contains(t, generated(t, "node/codec.gen.go"), "x.Files[i] = ref[*File](r)",
				"a file list admits files alone")
		})

		t.Run("fails the generation for a type it cannot write", func(t *testing.T) {
			t.Parallel()

			_, err := model.Generate(schemaModule(t, gaugeSchema))
			assert.HasError(t, err, "a float field has no binary encoding")
			assert.Contains(t, err.Error(), "node/codec.gen.go", "the error names the codec file")
		})
	})

	t.Run("documentation", func(t *testing.T) {
		t.Parallel()

		t.Run("contains the words of the schema", func(t *testing.T) {
			t.Parallel()

			kinds := generated(t, "node/kinds.gen.go")
			for _, want := range []string{
				"// Struct is a type values can be made of",
				"// This is the node spelling of the kind.",
				"// no value of it can be made directly",
			} {
				assert.Contains(t, kinds, strings.Join(strings.Fields(want), " "),
					"the models contain the words of the schema")
			}
		})
	})
}
