package model_test

import (
	"strings"
	"testing"

	"go.dokimi.dev/assert"

	"go.dokimi.dev/eidos/core/internal/gen/model"
)

// reachSchema is a schema shaped the way the kernel's own is not:
// a kind that reaches a fact only through a descent field, a
// fact-carrying kind whose descent field is the marker, and field
// names on both sides of the acronym rule.
const reachSchema = "// Root holds things and states nothing itself.\n" +
	"type Root struct {\n" +
	"\tThings []*Thing `eidos:\"emit,walk\"`\n" +
	"}\n\n" +
	"// Thing states a fact and holds any declaration.\n" +
	"type Thing struct {\n" +
	"\tAsync  bool     `eidos:\"emit,fact=Async\"`\n" +
	"\tDecls  []Symbol `eidos:\"emit,walk\"`\n" +
	"\tIDList []string `eidos:\"both\"`\n" +
	"\tcount  int      `eidos:\"both\"`\n" +
	"}\n"

// Rendering decides the spellings a template emits, so its cases
// read the generated bytes rather than the view: what a caller
// sees is the file, not the intermediate form.
func TestRender(t *testing.T) {
	t.Parallel()

	// generated returns one rendered file with its column padding
	// collapsed, so a case reads the spelling rather than the
	// alignment gofmt chose.
	generated := func(t *testing.T, path string) string {
		t.Helper()

		set, err := model.Generate(moduleRoot(t))
		assert.NoError(t, err, "the schema generates")
		body, ok := set[path]
		assert.True(t, ok, "the case reads a file the generator owns")
		return strings.Join(strings.Fields(string(body)), " ")
	}

	// rendered is generated over a written schema rather than the
	// kernel's own.
	rendered := func(t *testing.T, schema, path string) string {
		t.Helper()

		set, err := model.Generate(schemaModule(t, schema))
		assert.NoError(t, err, "the written schema generates")
		body, ok := set[path]
		assert.True(t, ok, "the case reads a file the generator owns")
		return strings.Join(strings.Fields(string(body)), " ")
	}

	t.Run("JSON keys", func(t *testing.T) {
		t.Parallel()

		t.Run("lower an acronym as one word", func(t *testing.T) {
			t.Parallel()

			kinds := generated(t, "node/kinds.gen.go")
			assert.Contains(t, kinds, `json:"id,omitzero"`,
				"an acronym lowers as one word")
			assert.NotContains(t, kinds, `json:"iD`,
				"never by its first letter alone")
		})

		t.Run("keep an ordinary name camel-cased", func(t *testing.T) {
			t.Parallel()

			assert.Contains(t, generated(t, "node/kinds.gen.go"), `json:"typeParams,omitzero"`,
				"an ordinary name camel-cases")
		})

		t.Run("break an acronym before the word that follows it", func(t *testing.T) {
			t.Parallel()

			assert.Contains(t, rendered(t, reachSchema, "node/kinds.gen.go"),
				`json:"idList,omitzero"`,
				"the last capital opens the next word, so IDList lowers to idList")
		})

		t.Run("leave a name that carries no capital", func(t *testing.T) {
			t.Parallel()

			assert.Contains(t, rendered(t, reachSchema, "node/kinds.gen.go"),
				`json:"count,omitzero"`,
				"a field already lowercase keeps its spelling")
		})
	})

	t.Run("sides", func(t *testing.T) {
		t.Parallel()

		t.Run("the node model carries a position and no origin", func(t *testing.T) {
			t.Parallel()

			kinds := generated(t, "node/kinds.gen.go")
			assert.Contains(t, kinds, "Pos position.Pos",
				"the node model carries a position")
			assert.NotContains(t, kinds, "Origin symbol.Identity",
				"and no origin, which belongs to emit")
		})

		t.Run("the emit model carries an origin and no position", func(t *testing.T) {
			t.Parallel()

			kinds := generated(t, "emit/kinds.gen.go")
			assert.Contains(t, kinds, "Origin",
				"the emit model carries an origin")
			assert.Contains(t, kinds, "position.Pos{}",
				"and returns the zero position")
		})

		t.Run("a slot exists on the emit side alone", func(t *testing.T) {
			t.Parallel()

			assert.Contains(t, generated(t, "emit/kinds.gen.go"), "Fields Slot[*Field]",
				"the emit model holds slot storage")
			assert.NotContains(t, generated(t, "node/kinds.gen.go"), "Slot[",
				"and the node model holds none")
		})

		t.Run("the body exists on the emit side alone", func(t *testing.T) {
			t.Parallel()

			assert.Contains(t, generated(t, "emit/kinds.gen.go"), `json:"body,omitzero"`,
				"the emit callables carry their content")
			assert.NotContains(t, generated(t, "node/kinds.gen.go"), `json:"body,omitzero"`,
				"and the node model never does")
		})

		t.Run("a marker field carries the dispatching slice", func(t *testing.T) {
			t.Parallel()

			assert.Contains(t, generated(t, "node/kinds.gen.go"), "Decls Symbols",
				"a marker-typed field is typed Symbols, so it can decode")
		})

		t.Run("the node model names itself and the emit model does not", func(t *testing.T) {
			t.Parallel()

			assert.Contains(t, generated(t, "node/kinds.gen.go"),
				"func (x *Struct) Identity() symbol.Identity",
				"a node declaration returns its identity, so a traversal can index by one")
			assert.NotContains(t, generated(t, "emit/kinds.gen.go"),
				"Identity() symbol.Identity",
				"the emit model returns none: an emit declaration has an origin instead")
		})

		t.Run("the match surface generates per subject kind", func(t *testing.T) {
			t.Parallel()

			matches := generated(t, "match.gen.go")
			assert.Contains(t, matches,
				"func OnInterface[E Effect](h func(*InterfaceMatch, E) error) Rule",
				"a marked kind gets its constructor and Match type")
			assert.NotContains(t, matches, "OnTypeParam",
				"an unmarked kind gets neither: the model bounds the set")
			assert.Contains(t, generated(t, "match.gen_test.go"), "func TestMatches",
				"the generated twin holds every kind to the lowering")
		})

		t.Run("the emit walk returns origins by function", func(t *testing.T) {
			t.Parallel()

			walk := generated(t, "emit/walk.gen.go")
			assert.Contains(t, walk,
				"func OriginOf(s symbol.Symbol) (symbol.Identity, bool)",
				"a subset of emit kinds carries origin storage, so a function returns it")
			assert.NotContains(t, generated(t, "node/walk.gen.go"), "OriginOf",
				"the node side has identities, never origins")
		})

		t.Run("the node walk returns the declarations it yields", func(t *testing.T) {
			t.Parallel()

			walk := generated(t, "node/walk.gen.go")
			for _, want := range []string{
				"type Declaration interface",
				"func Declarations(s symbol.Symbol) iter.Seq[Declaration]",
			} {
				assert.Contains(t, walk, want,
					"the node walk returns the declarations it yields")
			}
			assert.NotContains(t, generated(t, "emit/walk.gen.go"), "Declaration",
				"which only the identity-bearing side can")
		})
	})

	t.Run("facts", func(t *testing.T) {
		t.Parallel()

		t.Run("a kind reaching a fact only through a child joins the traversal", func(t *testing.T) {
			t.Parallel()

			facts := rendered(t, reachSchema, "emit/facts.gen.go")
			assert.Contains(t, facts, "case *Root: for _, child := range x.Things { statedFacts(x, child, f) }",
				"a kind that states no fact of its own still descends, "+
					"because the fact it reaches is its child's")
			assert.NotContains(t, facts, "symbol.KindRoot:",
				"and states none directly, so coverage is not held against it")
		})

		t.Run("a marker descent field takes a child of the enclosing kind", func(t *testing.T) {
			t.Parallel()

			twin := rendered(t, reachSchema, "emit/facts.gen_test.go")
			assert.Contains(t, twin, "child := &Thing{}",
				"a field holding any kind takes a value of the kind that declares it, "+
					"which is always available")
			assert.Contains(t, twin, "child.Async = true",
				"and the child states the first fact its kind carries")
		})
	})

	t.Run("documentation", func(t *testing.T) {
		t.Parallel()

		t.Run("carries the schema's own words", func(t *testing.T) {
			t.Parallel()

			kinds := generated(t, "node/kinds.gen.go")
			for _, want := range []string{
				"// Struct is a type values can be made of",
				"// This is the node spelling of the kind.",
				"// no value of it can be made directly",
			} {
				assert.Contains(t, kinds, strings.Join(strings.Fields(want), " "),
					"the models carry the schema's own words")
			}
		})
	})
}
